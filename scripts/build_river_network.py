"""Link river stations to the stations upstream of them (config/river_network.yaml), used by the ML upstream features.

A link is kept only if (1) a D8 flow path on the Copernicus GLO-30 DEM from the upstream station
passes the downstream one (snap radius 150 m: at 300 m neighbouring tributaries merge), and
(2) the JPS station names agree: same river, or a tributary whose named river joins the downstream
station's river (TRIBUTARIES, each checked against the flow path, see below). `name` links are
added for same-river stations the DEM cannot order in flat coastal terrain.

Usage: python scripts/build_river_network.py [--dry-run]
"""
from __future__ import annotations

import argparse
import re
import sys
import tempfile
from pathlib import Path

import numpy as np
import pandas as pd
import rasterio
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from floodready.gis import flow, terrain  # noqa: E402
from floodready.ml.dataset import UPSTREAM_MAX_KM, haversine_km  # noqa: E402

DEM = ROOT / "data" / "raw" / "dem" / "Copernicus_DSM_COG_10_N03_00_E101_00_DEM.tif"
OUT = ROOT / "config" / "river_network.yaml"
SNAP_M = 150
BUFFER_M = 8_000
ALIAS_M = 60        # JPS lists some sites twice (e.g. "(F2)" copies): same place = same station

# river (as named in "Sg. X di Y") -> rivers it joins. Every pair is backed by D8 paths from the tributary's
# stations reaching the main river's stations with additive distances (a -> c == a -> b + b -> c); see the PR.
# Binjai/Bakul -> Kapar Kechil: not provable by D8 (flat coast); supported by the cached OSM waterways
# (data/raw/osm/BBR_waterways_r5000): "Sungai Kapar Kechil" runs west along lat 3.112 from lon 101.423 to 101.394
# (the Perepat station is on it) and "Sungai Bakul" runs west at ~3.13 N, 101.48 E, towards it.
# Not listed (so rejected): the reverse of a listed pair, which is a snap artefact where two channels are
# within 150 m (e.g. Klang -> Gombak, Selangor -> Kuang), and anything whose name carries no river.
TRIBUTARIES: dict[str, set[str]] = {
    "gombak": {"klang"}, "bunus": {"klang"}, "ampang": {"klang"}, "kemensah": {"klang"}, "kerayong": {"klang"},
    "kuyoh": {"klang"}, "penchala": {"klang"}, "rasau": {"klang"},
    "batu": {"gombak", "klang"}, "keroh": {"gombak", "klang"}, "toba": {"keroh", "gombak", "klang"},
    "binjai": {"kapar kechil"}, "bakul": {"kapar kechil"},
}
# Stations whose name has no "Sg. X di" but which sit on a named river
RIVER_OF_ID = {"3217002_": "klang"}          # Empangan Klang Gates: the dam on Sg. Klang
# Same-river stations the DEM cannot order (flat coast): (upstream id, downstream id, why)
_KLANG_WHY = ("same river (Sg. Klang), stations ordered towards the sea by position: longitudes 101.597 > 101.535 > 101.445 on a river "
              "that reaches the Strait of Malacca at ~101.35; the DEM path from Puchong Drop leaves the GLO-30 tile at lat 3.0")
MANUAL: list[tuple[str, str, str]] = [
    ("3015001_", "3015084_", _KLANG_WHY),      # Puchong Drop -> Taman Sri Muda
    ("3015084_", "3014080_", _KLANG_WHY),      # Taman Sri Muda -> Bandar Klang
]

HEADER = """# River network between JPS river stations: for each downstream station, the stations upstream of it.
# Generated by scripts/build_river_network.py (do not edit by hand; edit TRIBUTARIES / MANUAL in the script).
#
# How it was built:
#   1. D8 flow paths on the Copernicus GLO-30 DEM (pysheds; DEM clipped to the stations' bounding box + 8 km).
#      Each station is snapped to the highest-flow-accumulation cell within 150 m; the path from every
#      station is followed downhill and the stations it passes are its downstream stations.
#   2. A flow link is kept only if the station names agree: same river ("Sg. X di ..."), or a river that
#      joins the downstream station's river (tributaries listed in the script, each checked against the flow path).
#   3. method: flow = flow path and names agree; name = not (fully) confirmed by a flow path: the Klang chain
#      Puchong Drop -> Taman Sri Muda -> Bandar Klang (same named river; the DEM path leaves the tile at lat 3.0),
#      and every link that goes through it (closed transitively). Stations outside the DEM tile get no flow links.
#   path_km is the flow-path distance from the upstream station to the downstream one (null for `name` links).
#   4. Links longer than 15 km (flow-path distance; straight-line for `name` links) are dropped: see UPSTREAM_MAX_KM.
# Duplicate JPS listings of one site (within 60 m) are treated as the same station and share links.
"""


def river_of(name: str, gid: str | None = None) -> str:
    if gid in RIVER_OF_ID:
        return RIVER_OF_ID[gid]
    m = re.match(r"\s*(?:Sg\.|Sungai)\s+(.+?)\s+di\s+", name, flags=re.I)
    return m.group(1).strip().lower() if m else ""


def names_agree(up: str, down: str, up_id: str | None = None, down_id: str | None = None) -> bool:
    a, b = river_of(up, up_id), river_of(down, down_id)
    return bool(a) and bool(b) and (a == b or b in TRIBUTARIES.get(a, set()))


def load_stations() -> pd.DataFrame:
    s = pd.read_parquet(ROOT / "data" / "interim" / "stations.parquet")
    s = s[(s.kind == "wl") & s.thresholds_ok.astype(bool) & s.lat.notna()].drop_duplicates("graph_id")
    return s.reset_index(drop=True)


def aliases(stations: pd.DataFrame) -> dict[str, str]:
    """graph_id -> canonical graph_id of the same physical site."""
    canon: dict[str, str] = {}
    pts = [(r.graph_id, r.lat, r.lon) for r in stations.itertuples()]
    for gid, lat, lon in pts:
        for other, la, lo in pts:
            if other in canon.values() and np.hypot((lat - la) * 111_320, (lon - lo) * 111_320 * np.cos(np.radians(lat))) <= ALIAS_M:
                canon[gid] = other
                break
        else:
            canon[gid] = gid
    return canon


def flow_links(stations: pd.DataFrame, canon: dict[str, str]) -> tuple[dict, list[str]]:
    """{downstream: {upstream: path_km}} from D8 on the DEM, plus ids skipped for lying outside the tile."""
    with rasterio.open(DEM) as r:
        b = r.bounds
    inside = stations[(stations.lat > b.bottom + 0.003) & (stations.lat < b.top - 0.003) & (stations.lon > b.left + 0.003) & (stations.lon < b.right - 0.003)]
    skipped = sorted(set(stations.graph_id) - set(inside.graph_id))
    sites = inside[inside.graph_id.map(canon) == inside.graph_id]
    lat0, lat1, lon0, lon1 = sites.lat.min(), sites.lat.max(), sites.lon.min(), sites.lon.max()
    lat_c, lon_c = (lat0 + lat1) / 2, (lon0 + lon1) / 2
    half_m = max((lat1 - lat0) / 2 * terrain.M_PER_DEG, (lon1 - lon0) / 2 * terrain.M_PER_DEG * np.cos(np.radians(lat_c))) + BUFFER_M
    with tempfile.TemporaryDirectory() as tmp:
        clip = terrain.clip_dem(DEM, Path(tmp) / "clip.tif", lat_c, lon_c, half_m)
        grid = flow.flow_grid(clip)
    pts = [(r.graph_id, r.lat, r.lon) for r in sites.itertuples()]
    links: dict[str, dict[str, float]] = {}
    for sid, lat, lon in pts:
        start = flow.snap_to_stream(grid, lat, lon, radius_m=SNAP_M)
        if start is None:
            continue
        for down, dist_m in flow.stations_downstream(grid, lat, lon, pts, snap_m=SNAP_M, start=start, exclude=sid):
            links.setdefault(down, {})[sid] = round(dist_m / 1000, 1)
    return links, skipped


def close_transitively(kept: dict[str, dict[str, tuple[str, float | None]]]) -> None:
    """If A is upstream of B and B of C, A is upstream of C (needed once `name` links join flow links)."""
    changed = True
    while changed:
        changed = False
        for down, ups in list(kept.items()):
            for mid, (m1, k1) in list(ups.items()):
                for up, (m2, k2) in kept.get(mid, {}).items():
                    if up != down and up not in ups:
                        total = round(k1 + k2, 1) if k1 is not None and k2 is not None else None
                        ups[up] = ("flow" if m1 == m2 == "flow" else "name", total)
                        changed = True


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    stations = load_stations()
    names = dict(zip(stations.graph_id, stations.name))
    canon = aliases(stations)
    members: dict[str, list[str]] = {}
    for gid, c in canon.items():
        members.setdefault(c, []).append(gid)

    raw, skipped = flow_links(stations, canon)
    kept: dict[str, dict[str, tuple[str, float | None]]] = {}
    rejected = []
    for down, ups in raw.items():
        for up, km in ups.items():
            if names_agree(names[up], names[down], up, down):
                kept.setdefault(down, {})[up] = ("flow", km)
            else:
                rejected.append((up, down, km))
    for up, down, why in MANUAL:
        kept.setdefault(canon[down], {}).setdefault(canon[up], ("name", None))
        print(f"manual: {names[up]} -> {names[down]}: {why}")

    close_transitively(kept)
    coords = {r.graph_id: (r.lat, r.lon) for r in stations.itertuples()}
    capped = []
    for down, ups in kept.items():
        for up in list(ups):
            km = ups[up][1]
            if km is None:      # `name` link: no flow path, use the straight-line distance
                km = float(haversine_km(*coords[up], *coords[down]))
            if km > UPSTREAM_MAX_KM:
                capped.append((up, down, km))
                del ups[up]
    print(f"dropped {len(capped)} links farther than {UPSTREAM_MAX_KM} km")
    out: dict[str, list[dict]] = {}
    for down, ups in sorted(kept.items()):
        links = [{"id": m, "method": meth, "path_km": km} for up, (meth, km) in sorted(ups.items()) for m in sorted(members[up])]
        for m in members[down]:
            out[m] = links
    text = HEADER + "\n" + yaml.safe_dump(out, sort_keys=True, default_flow_style=None, width=140)

    print(f"stations with thresholds and coordinates: {len(stations)}; outside the DEM tile (skipped): {len(skipped)}")
    for s in skipped:
        print(f"   skipped {s} {names[s]}")
    print(f"flow links found: {sum(len(v) for v in raw.values())}; kept after name check: {sum(len(v) for v in kept.values())}")
    for down, ups in sorted(kept.items()):
        for up, (meth, km) in ups.items():
            print(f"   KEEP {names[up]} ({up}) -> {names[down]} ({down}) [{meth}, {km} km]")
    for up, down, km in sorted(rejected, key=lambda r: names[r[1]]):
        print(f"   REJECT {names[up]} ({up}) -> {names[down]} ({down}) [{km} km]: {river_of(names[up], up)!r} vs {river_of(names[down], down)!r}")
    if not args.dry_run:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
